#!/bin/sh
# Exports the iOS Xcode project into build/ios/ and stamps the build, so the HUD shows
# which version is running on the device. After running this, press Run in Xcode.
set -e
cd "$(dirname "$0")/.."
GODOT=/Applications/Godot.app/Contents/MacOS/Godot

# Never ship a build that fails the walkthrough tests.
if ! ./tools/run_tests.sh > /dev/null; then
	echo "Tests failed: not exporting. Run tools/run_tests.sh to see why."
	exit 1
fi
echo "All tests passed."

COMMIT=$(git rev-parse --short HEAD)
if ! git diff --quiet HEAD; then COMMIT="$COMMIT+changes"; fi
STAMP="$COMMIT · $(date '+%Y-%m-%d %H:%M')"
printf 'extends RefCounted\n## Generated by tools/export_ios.sh. Do not edit or commit.\nconst TEXT: String = "%s"\n' "$STAMP" > build_info.gd

mkdir -p build/ios
touch build/.gdignore
"$GODOT" --headless --path . --import
"$GODOT" --headless --path . --export-debug "iOS" build/ios/AirportIdle.ipa
echo "Exported build: $STAMP"
echo "Now press Run in Xcode. The HUD shows this stamp at the top of the screen."
